"""Company/branch/employee/customer/supplier/product generation for the bulk
demo-data seed. Every company gets exactly what production's real signup
flow gives it (seed_company_defaults()'s control accounts, voucher types,
tax codes) plus a fixed-size roster of branches/employees/master data, so
the transactions generated by ledger.py always have valid accounts and
parties to reference.

Small-N data (companies, branches, admin users — at most ~1,100 rows total
across a 100-company run) uses plain ORM db.add()/flush, matching every
existing seed script in this repo. Larger per-company pools (employees,
customers, suppliers, products) use SQLAlchemy 2.0 Core bulk inserts
(db.execute(insert(Model), [rows])), since add_seed_50_real.py's row-by-row
db.add() pattern does not scale past a few hundred rows per table.
"""
